#!/usr/bin/env python3
"""
Plot comparison CSV files and generate:
1) Per-bs theory vs real probability distributions
2) Per-bs absolute error by m
3) Summary error metrics across bs
4) Overlay plots across bs

This script is compatible with the routed-token comparison outputs generated by
compare_token_distribution.py as well as the older comparison CSV format.
"""

from __future__ import annotations

import argparse
import csv
import math
import re
from pathlib import Path
from typing import Dict, List

import matplotlib.pyplot as plt


def read_summary_csv(path: Path) -> List[Dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def read_comparison_csv(path: Path) -> List[Dict[str, float]]:
    rows: List[Dict[str, float]] = []
    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append({
                "m": int(row["m"]),
                "theory_prob": float(row["theory_prob"]),
                "real_prob": float(row["real_prob"]),
                "abs_error": float(row["abs_error"]),
                "sMAPE_percent": float(row["sMAPE_percent"]),
            })
    return rows


def smape(a: float, b: float) -> float:
    denom = abs(a) + abs(b)
    if denom == 0:
        return 0.0
    return 200.0 * abs(a - b) / denom


def build_summary_from_comparison_files(input_dir: Path) -> List[Dict[str, str]]:
    summary_rows: List[Dict[str, str]] = []
    pattern = re.compile(r"ep(?P<ep>\d+)_theorybs(?P<theory_bs>\d+)_vs_realbs(?P<real_bs>\d+)\.csv$")

    for comparison_path in sorted(input_dir.glob("ep*_theorybs*_vs_realbs*.csv")):
        match = pattern.match(comparison_path.name)
        if not match:
            continue

        comp_rows = read_comparison_csv(comparison_path)
        if not comp_rows:
            continue

        abs_errors = [row["abs_error"] for row in comp_rows]
        squared_errors = [row["abs_error"] ** 2 for row in comp_rows]
        smapes = [smape(row["theory_prob"], row["real_prob"]) for row in comp_rows]
        l1 = sum(abs_errors)
        size = len(comp_rows)

        summary_rows.append({
            "ep": match.group("ep"),
            "theory_source_file_bs": match.group("theory_bs"),
            "analysis_bs": match.group("real_bs"),
            "L1": f"{l1:.12f}",
            "TVD": f"{0.5 * l1:.12f}",
            "MAE": f"{(l1 / size) if size else 0.0:.12f}",
            "RMSE": f"{math.sqrt(sum(squared_errors) / size) if size else 0.0:.12f}",
            "mean_sMAPE_percent": f"{(sum(smapes) / size) if size else 0.0:.12f}",
            "max_abs_error": f"{max(abs_errors) if abs_errors else 0.0:.12f}",
            "comparison_csv": str(comparison_path),
        })

    return sorted(summary_rows, key=lambda row: int(row["analysis_bs"]))


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def infer_plot_context(input_dir: Path) -> Dict[str, str]:
    dir_name = input_dir.name.lower()
    if "routed_tokens" in dir_name:
        return {
            "metric_name": "Max Routed Tokens Per GPU",
            "dist_title": "Predicted vs Real Distribution of Max Routed Tokens Per GPU",
            "combined_real_title": "Real Distributions of Max Routed Tokens Per GPU Across Batch Sizes",
            "combined_theory_title": "Predicted Distributions of Max Routed Tokens Per GPU Across Batch Sizes",
            "overlay_title": "Predicted vs Real Mean Trend Across Batch Sizes",
        }

    return {
        "metric_name": "Max Load",
        "dist_title": "Theory vs Real Probability Distribution",
        "combined_real_title": "Real Probability Distributions Across Batch Sizes",
        "combined_theory_title": "Theory Probability Distributions Across Batch Sizes",
        "overlay_title": "Theory vs Real Mean Trend Across Batch Sizes",
    }


def save_distribution_plot(
    rows: List[Dict[str, float]],
    bs: int,
    out_path: Path,
    hide_all_zero_rows: bool,
    title_prefix: str,
    metric_name: str,
) -> None:
    filtered = rows
    if hide_all_zero_rows:
        filtered = [
            row for row in rows
            if row["theory_prob"] != 0.0 or row["real_prob"] != 0.0
        ] or rows

    xs = [row["m"] for row in filtered]
    theory = [row["theory_prob"] for row in filtered]
    real = [row["real_prob"] for row in filtered]

    plt.figure(figsize=(10, 6))
    plt.plot(xs, theory, marker="o", label="Theory")
    plt.plot(xs, real, marker="s", label="Real")
    plt.xlabel(metric_name)
    plt.ylabel("Probability")
    plt.title(f"{title_prefix} (bs={bs})")
    plt.xticks(xs)
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def save_abs_error_plot(
    rows: List[Dict[str, float]],
    bs: int,
    out_path: Path,
    hide_all_zero_rows: bool,
    metric_name: str,
) -> None:
    filtered = rows
    if hide_all_zero_rows:
        filtered = [
            row for row in rows
            if row["theory_prob"] != 0.0 or row["real_prob"] != 0.0 or row["abs_error"] != 0.0
        ] or rows

    xs = [row["m"] for row in filtered]
    abs_errors = [row["abs_error"] for row in filtered]

    plt.figure(figsize=(10, 6))
    plt.bar(xs, abs_errors)
    plt.xlabel(metric_name)
    plt.ylabel("Absolute error")
    plt.title(f"Absolute Error by {metric_name} (bs={bs})")
    plt.xticks(xs)
    plt.grid(True, axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def save_combined_distribution_plot(
    summary_rows: List[Dict[str, str]],
    out_path: Path,
    mode: str,
    title: str,
    metric_name: str,
) -> None:
    plt.figure(figsize=(11, 7))

    for row in summary_rows:
        bs = int(row["analysis_bs"])
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            continue
        comp_rows = read_comparison_csv(comparison_path)
        filtered = [
            r for r in comp_rows
            if r["theory_prob"] != 0.0 or r["real_prob"] != 0.0
        ] or comp_rows

        xs = [r["m"] for r in filtered]
        if mode == "real":
            ys = [r["real_prob"] for r in filtered]
            label = f"real bs={bs}"
        else:
            ys = [r["theory_prob"] for r in filtered]
            label = f"theory bs={bs}"
        plt.plot(xs, ys, marker="o", label=label)

    plt.xlabel(metric_name)
    plt.ylabel("Probability")
    plt.title(title)
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def expected_value(rows: List[Dict[str, float]], key: str) -> float:
    return sum(row["m"] * row[key] for row in rows)


def save_mean_trend_plot(
    summary_rows: List[Dict[str, str]],
    out_path: Path,
    metric_name: str,
    title: str,
) -> None:
    ordered = sorted(summary_rows, key=lambda row: int(row["analysis_bs"]))
    xs = []
    theory_means = []
    real_means = []

    for row in ordered:
        bs = int(row["analysis_bs"])
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            continue

        comp_rows = read_comparison_csv(comparison_path)
        xs.append(bs)
        theory_means.append(expected_value(comp_rows, "theory_prob"))
        real_means.append(expected_value(comp_rows, "real_prob"))

    plt.figure(figsize=(10, 6))
    plt.plot(xs, theory_means, marker="o", label="Theory mean")
    plt.plot(xs, real_means, marker="s", label="Real mean")
    plt.xlabel("Batch size (bs)")
    plt.ylabel(f"Expected {metric_name}")
    plt.title(title)
    plt.xscale("log", base=2)
    plt.xticks(xs, [str(x) for x in xs])
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def save_abs_error_overlay_plot(
    summary_rows: List[Dict[str, str]],
    out_path: Path,
    metric_name: str,
) -> None:
    plt.figure(figsize=(11, 7))

    for row in sorted(summary_rows, key=lambda item: int(item["analysis_bs"])):
        bs = int(row["analysis_bs"])
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            continue

        comp_rows = read_comparison_csv(comparison_path)
        filtered = [r for r in comp_rows if r["abs_error"] != 0.0] or comp_rows
        xs = [r["m"] for r in filtered]
        ys = [r["abs_error"] for r in filtered]
        plt.plot(xs, ys, marker="o", label=f"bs={bs}")

    plt.xlabel(metric_name)
    plt.ylabel("Absolute error")
    plt.title("Absolute Error Distribution Across Batch Sizes")
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def save_abs_error_heatmap(
    summary_rows: List[Dict[str, str]],
    out_path: Path,
    metric_name: str,
) -> None:
    ordered = sorted(summary_rows, key=lambda item: int(item["analysis_bs"]))
    if not ordered:
        return

    bs_values = []
    row_vectors = []
    max_m = 0

    for row in ordered:
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            continue
        comp_rows = read_comparison_csv(comparison_path)
        if not comp_rows:
            continue
        bs_values.append(int(row["analysis_bs"]))
        max_m = max(max_m, max(r["m"] for r in comp_rows))
        row_vectors.append({r["m"]: r["abs_error"] for r in comp_rows})

    if not row_vectors:
        return

    heatmap = []
    for vec in row_vectors:
        heatmap.append([vec.get(m, 0.0) for m in range(max_m + 1)])

    plt.figure(figsize=(12, 6))
    image = plt.imshow(heatmap, aspect="auto", origin="lower", cmap="viridis")
    plt.colorbar(image, label="Absolute error")
    plt.xlabel(metric_name)
    plt.ylabel("Batch size index")
    plt.title("Absolute Error Heatmap Across Batch Sizes")
    plt.xticks(
        ticks=list(range(0, max_m + 1, max(1, (max_m + 1) // 12))),
        labels=[str(x) for x in range(0, max_m + 1, max(1, (max_m + 1) // 12))],
    )
    plt.yticks(ticks=list(range(len(bs_values))), labels=[str(bs) for bs in bs_values])
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def save_summary_metric_plot(
    summary_rows: List[Dict[str, str]],
    metric: str,
    out_path: Path,
) -> None:
    ordered = sorted(summary_rows, key=lambda row: int(row["analysis_bs"]))
    xs = [int(row["analysis_bs"]) for row in ordered]
    ys = [float(row[metric]) for row in ordered]

    plt.figure(figsize=(10, 6))
    plt.plot(xs, ys, marker="o")
    plt.xlabel("bs")
    plt.ylabel(metric)
    plt.title(f"{metric} across bs")
    plt.xscale("log", base=2)
    plt.xticks(xs, [str(x) for x in xs])
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def compute_tvd_from_rows(rows: List[Dict[str, float]]) -> float:
    return 0.5 * sum(abs(row["theory_prob"] - row["real_prob"]) for row in rows)


def remove_spike_and_renormalize(
    rows: List[Dict[str, float]],
    spike_m: int,
) -> List[Dict[str, float]]:
    filtered = [dict(row) for row in rows if row["m"] != spike_m]
    theory_mass = sum(row["theory_prob"] for row in filtered)
    real_mass = sum(row["real_prob"] for row in filtered)

    normalized = []
    for row in filtered:
        normalized.append({
            **row,
            "theory_prob": (row["theory_prob"] / theory_mass) if theory_mass > 0 else 0.0,
            "real_prob": (row["real_prob"] / real_mass) if real_mass > 0 else 0.0,
        })

    return normalized


def save_spike_removed_tvd_plot(
    summary_rows: List[Dict[str, str]],
    out_path: Path,
) -> None:
    ordered = sorted(summary_rows, key=lambda row: int(row["analysis_bs"]))
    xs = []
    original_tvds = []
    spike_removed_tvds = []

    for row in ordered:
        bs = int(row["analysis_bs"])
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            continue

        comp_rows = read_comparison_csv(comparison_path)
        spike_m = 2 * bs

        xs.append(bs)
        original_tvds.append(compute_tvd_from_rows(comp_rows))
        spike_removed_rows = remove_spike_and_renormalize(comp_rows, spike_m=spike_m)
        spike_removed_tvds.append(compute_tvd_from_rows(spike_removed_rows))

    plt.figure(figsize=(10, 6))
    plt.plot(xs, original_tvds, marker="o", label="Original TVD")
    plt.plot(xs, spike_removed_tvds, marker="s", label="Spike-removed TVD")
    plt.xlabel("Batch size (bs)")
    plt.ylabel("TVD")
    plt.title("TVD Before and After Removing Spike Bin (m = 2 * bs)")
    plt.xscale("log", base=2)
    plt.xticks(xs, [str(x) for x in xs])
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Plot theory-vs-real distribution comparison results from saved CSV files."
    )
    parser.add_argument(
        "--input-dir",
        default="./output/distribution_compare_ep4_bs1_routed_tokens",
        help="Directory containing summary.csv and comparison CSV files.",
    )
    parser.add_argument(
        "--output-dir",
        default="",
        help="Directory to save plots. Defaults to <input-dir>/plots",
    )
    parser.add_argument(
        "--show-zero-rows",
        action="store_true",
        help="Include rows where both theory and real are 0 in per-bs plots.",
    )
    args = parser.parse_args()

    input_dir = Path(args.input_dir)
    if not input_dir.exists():
        raise FileNotFoundError(f"Input directory not found: {input_dir}")

    output_dir = Path(args.output_dir) if args.output_dir else input_dir / "plots"
    ensure_dir(output_dir)
    context = infer_plot_context(input_dir)

    summary_path = input_dir / "summary.csv"
    if summary_path.exists():
        summary_rows = read_summary_csv(summary_path)
    else:
        summary_rows = build_summary_from_comparison_files(input_dir)

    if not summary_rows:
        raise RuntimeError(
            f"No usable summary data found in {input_dir}. "
            "Expected summary.csv or comparison CSV files."
        )

    for row in summary_rows:
        bs = int(row["analysis_bs"])
        comparison_path = Path(row["comparison_csv"])
        if not comparison_path.exists():
            print(f"[skip] comparison csv not found: {comparison_path}")
            continue

        comp_rows = read_comparison_csv(comparison_path)

        dist_path = output_dir / f"distribution_bs{bs}.png"
        err_path = output_dir / f"abs_error_bs{bs}.png"

        save_distribution_plot(
            rows=comp_rows,
            bs=bs,
            out_path=dist_path,
            hide_all_zero_rows=not args.show_zero_rows,
            title_prefix=context["dist_title"],
            metric_name=context["metric_name"],
        )
        save_abs_error_plot(
            rows=comp_rows,
            bs=bs,
            out_path=err_path,
            hide_all_zero_rows=not args.show_zero_rows,
            metric_name=context["metric_name"],
        )
        print(f"[saved] {dist_path}")
        print(f"[saved] {err_path}")

    real_combined_path = output_dir / "real_distributions_all_bs.png"
    theory_combined_path = output_dir / "theory_distributions_all_bs.png"
    trend_path = output_dir / "mean_trend_theory_vs_real.png"
    abs_error_overlay_path = output_dir / "abs_error_overlay_all_bs.png"
    abs_error_heatmap_path = output_dir / "abs_error_heatmap_all_bs.png"
    spike_removed_tvd_path = output_dir / "summary_TVD_spike_removed.png"

    save_combined_distribution_plot(
        summary_rows,
        real_combined_path,
        mode="real",
        title=context["combined_real_title"],
        metric_name=context["metric_name"],
    )
    save_combined_distribution_plot(
        summary_rows,
        theory_combined_path,
        mode="theory",
        title=context["combined_theory_title"],
        metric_name=context["metric_name"],
    )
    save_mean_trend_plot(
        summary_rows,
        trend_path,
        metric_name=context["metric_name"],
        title=context["overlay_title"],
    )
    save_abs_error_overlay_plot(
        summary_rows,
        abs_error_overlay_path,
        metric_name=context["metric_name"],
    )
    save_abs_error_heatmap(
        summary_rows,
        abs_error_heatmap_path,
        metric_name=context["metric_name"],
    )
    save_spike_removed_tvd_plot(
        summary_rows,
        spike_removed_tvd_path,
    )
    print(f"[saved] {real_combined_path}")
    print(f"[saved] {theory_combined_path}")
    print(f"[saved] {trend_path}")
    print(f"[saved] {abs_error_overlay_path}")
    print(f"[saved] {abs_error_heatmap_path}")
    print(f"[saved] {spike_removed_tvd_path}")

    for metric in ["L1", "TVD", "MAE", "RMSE", "mean_sMAPE_percent", "max_abs_error"]:
        metric_path = output_dir / f"summary_{metric}.png"
        save_summary_metric_plot(summary_rows, metric, metric_path)
        print(f"[saved] {metric_path}")

    print(f"\nDone. Plots saved to: {output_dir}")


if __name__ == "__main__":
    main()
